/**
 * 获取 HTTP 状态码对应的中文消息
 */
export function getHttpStatusMessageZh(statusCode: number): string {
  return HTTP_STATUS_MESSAGE_ZH[statusCode] ?? '操作成功';
}

/**
 * 检查是否为默认 HTTP 状态码消息
 */
export function isDefaultHttpStatusMessage(
  statusCode: number,
  message: string,
): boolean {
  return STATUS_CODES[statusCode] === message;
}
